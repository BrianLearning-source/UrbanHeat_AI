CREATE SCHEMA IF NOT EXISTS extensions;

CREATE EXTENSION IF NOT EXISTS postgis
    WITH SCHEMA extensions;

-- =========================================================
-- Table: public.malang_climate_pilot
-- =========================================================

CREATE SEQUENCE public.malang_climate_pilot_id_seq
    AS integer
    START WITH 1
    INCREMENT BY 1
    MINVALUE 1
    MAXVALUE 2147483647
    CACHE 1
    NO CYCLE;

CREATE TABLE public.malang_climate_pilot (
    id integer NOT NULL
        DEFAULT nextval(
            'public.malang_climate_pilot_id_seq'::regclass
        ),
    date date NOT NULL,
    latitude numeric NOT NULL,
    longitude numeric NOT NULL,
    lst numeric,
    ndvi numeric,
    ndbi numeric,
    created_at timestamp with time zone
        DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT malang_climate_pilot_pkey
        PRIMARY KEY (id)
);

ALTER SEQUENCE public.malang_climate_pilot_id_seq
    OWNED BY public.malang_climate_pilot.id;

CREATE INDEX idx_malang_date
    ON public.malang_climate_pilot USING btree (date);

CREATE INDEX idx_malang_lat_lon
    ON public.malang_climate_pilot
    USING btree (latitude, longitude);


-- =========================================================
-- Table: public.urban_heat_data
-- =========================================================

CREATE TABLE public.urban_heat_data (
    id bigint GENERATED BY DEFAULT AS IDENTITY (
        START WITH 1
        INCREMENT BY 1
        MINVALUE 1
        MAXVALUE 9223372036854775807
        CACHE 1
        NO CYCLE
    ) NOT NULL,
    "NDVI" double precision,
    "NDBI" double precision,
    "LST_Celsius" double precision,
    ".geo" text,
    geom extensions.geometry(Point, 4326),
    created_at timestamp with time zone NOT NULL
        DEFAULT timezone('utc'::text, now()),
    CONSTRAINT urban_heat_data_pkey
        PRIMARY KEY (id)
);

CREATE INDEX urban_heat_data_geom_idx
    ON public.urban_heat_data USING gist (geom);
